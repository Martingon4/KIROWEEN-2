#!/usr/bin/env node
/**
 * Generates the curated solar scenarios for a site (FT-11):
 *   data/sites/<slug>/solar-scenarios.json   versioned source, checksum in manifest.json
 *   supabase/seeds/solar.sql                 rows for public.analysis_scenarios
 *
 * Run after changing scenario definitions:  node scripts/generate-solar-scenarios.mjs
 * Verify in CI that committed files match:  node scripts/generate-solar-scenarios.mjs --check
 *
 * SunCalc measures azimuth from the south towards the west. The stored azimuthRad is
 * clockwise from north: mod(azimuth + PI, 2*PI). Scenarios below 10 degrees of solar
 * elevation are recorded in `excluded` and never reach the database.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import SunCalc from "suncalc";

const SUNCALC_VERSION = JSON.parse(
  readFileSync(new URL("../node_modules/suncalc/package.json", import.meta.url), "utf8"),
).version;
const GENERATOR = `suncalc@${SUNCALC_VERSION}`;
const MIN_ELEVATION_RAD = (10 * Math.PI) / 180;
const CHECK_MODE = process.argv.includes("--check");

const SITES = [
  {
    slug: "zocalo-puebla",
    scenarioLocalDatetimes: [
      { slug: "equinox-1000", localDatetime: "2027-03-20T10:00:00" },
      { slug: "equinox-1600", localDatetime: "2027-03-20T16:00:00" },
      { slug: "equinox-1900", localDatetime: "2027-03-20T19:00:00" },
    ],
  },
];

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const round6 = (value) => Math.round(value * 1e6) / 1e6;

/** Area-weighted centroid of a simple polygon ring of [lng, lat] pairs. */
function polygonCentroid(ring) {
  let twiceArea = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const cross = x0 * y1 - x1 * y0;
    twiceArea += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  return [round6(cx / (3 * twiceArea)), round6(cy / (3 * twiceArea))];
}

/** UTC instant of a wall-clock time in an IANA zone, via one Intl offset pass. */
function zonedTimeToUtc(localDatetime, timeZone) {
  const guess = Date.parse(`${localDatetime}Z`);
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat("en-US", {
      timeZone,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    })
      .formatToParts(new Date(guess))
      .filter((part) => part.type !== "literal")
      .map((part) => [part.type, part.value]),
  );
  const wallAsUtc = Date.UTC(
    Number(parts.year),
    Number(parts.month) - 1,
    Number(parts.day),
    Number(parts.hour) % 24,
    Number(parts.minute),
    Number(parts.second),
  );
  return new Date(guess - (wallAsUtc - guess));
}

function buildDataset(site) {
  const dir = path.join("data", "sites", site.slug);
  const manifest = JSON.parse(readFileSync(path.join(dir, "manifest.json"), "utf8"));
  const baseline = JSON.parse(readFileSync(path.join(dir, "baseline.geojson"), "utf8"));
  const ring = baseline.features[0].geometry.coordinates[0];
  const [longitude, latitude] = polygonCentroid(ring);

  const scenarios = [];
  const excluded = [];
  for (const candidate of site.scenarioLocalDatetimes) {
    const instantUtc = zonedTimeToUtc(candidate.localDatetime, manifest.timezone);
    const position = SunCalc.getPosition(instantUtc, latitude, longitude);
    const azimuthRad = round6((position.azimuth + Math.PI + 2 * Math.PI) % (2 * Math.PI));
    const elevationRad = round6(position.altitude);
    if (elevationRad >= MIN_ELEVATION_RAD) {
      scenarios.push({
        slug: candidate.slug,
        localDatetime: candidate.localDatetime,
        timezone: manifest.timezone,
        instantUtc: instantUtc.toISOString(),
        azimuthRad,
        elevationRad,
      });
    } else {
      excluded.push({
        slug: candidate.slug,
        localDatetime: candidate.localDatetime,
        reason: "elevation_below_10deg",
      });
    }
  }

  return {
    manifest,
    dataset: {
      generator: GENERATOR,
      siteId: manifest.id,
      latitude,
      longitude,
      scenarios,
      excluded,
    },
  };
}

function seedSql(dataset) {
  const lines = dataset.scenarios.map(
    (scenario, index) =>
      `  (gen_random_uuid(), '${dataset.siteId}', '${scenario.slug}', ` +
      `'${scenario.localDatetime}', '${scenario.timezone}', '${scenario.instantUtc}', ` +
      `${scenario.azimuthRad}, ${scenario.elevationRad}, '${dataset.generator}', ` +
      `'${sha256(stableJson(dataset))}', ${index === 0 ? "true" : "false"})`,
  );
  return (
    `-- Generated by scripts/generate-solar-scenarios.mjs (${dataset.generator}). Do not edit by hand.\n` +
    `insert into public.analysis_scenarios (\n` +
    `  id, site_id, slug, local_datetime, timezone, instant_utc,\n` +
    `  azimuth_rad, elevation_rad, generator, dataset_checksum, is_default\n` +
    `)\nvalues\n${lines.join(",\n")}\n` +
    `on conflict (site_id, slug) do nothing;\n`
  );
}

const stableJson = (value) => `${JSON.stringify(value, null, 2)}\n`;

let failed = false;
for (const site of SITES) {
  const dir = path.join("data", "sites", site.slug);
  const { manifest, dataset } = buildDataset(site);
  const jsonText = stableJson(dataset);
  const checksum = sha256(jsonText);
  const manifestText = `${JSON.stringify(
    {
      ...manifest,
      checksum: { ...manifest.checksum, solarScenarios: checksum },
    },
    null,
    2,
  )}\n`;
  const sqlText = seedSql(dataset);

  const targets = [
    [path.join(dir, "solar-scenarios.json"), jsonText],
    [path.join(dir, "manifest.json"), manifestText],
    [path.join("supabase", "seeds", "solar.sql"), sqlText],
  ];
  for (const [file, content] of targets) {
    if (CHECK_MODE) {
      let current = null;
      try {
        current = readFileSync(file, "utf8");
      } catch {
        current = null;
      }
      if (current !== content) {
        console.error(`drift: ${file} does not match the generator output`);
        failed = true;
      }
    } else {
      writeFileSync(file, content);
      console.log(`wrote ${file}`);
    }
  }
  console.log(`dataset checksum: ${checksum}`);
}

if (failed) {
  console.error("solar scenario check failed; run scripts/generate-solar-scenarios.mjs");
  process.exit(1);
}
if (CHECK_MODE) console.log("solar scenarios match");
