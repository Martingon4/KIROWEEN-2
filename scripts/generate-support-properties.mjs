#!/usr/bin/env node
/**
 * Generates supabase/tests/018_support_properties.test.sql from fast-check (R7).
 *
 * Properties checked against the real database through set_support:
 *   - repeating support leaves the count unchanged (a user counts once);
 *   - withdrawing after supporting returns the count to its previous value;
 *   - repeating a withdrawal leaves the count unchanged;
 *   - after any interleaving of users and operations the count equals the number of
 *     distinct accounts currently supporting, and `supported` echoes the request.
 *
 * The sequences come from fast-check with a recorded seed, so the SQL file is
 * deterministic and reviewable. A counterexample found later is added to the
 * REGRESSIONS list below and replayed forever.
 *
 *   node scripts/generate-support-properties.mjs          write the file
 *   node scripts/generate-support-properties.mjs --check  fail if the file differs
 */
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import fc from "fast-check";

const SEED = 20260514;
const SEQUENCES = 40;
const USERS_PER_SEQUENCE = 3;
const MAX_OPS = 20;
const OUTPUT = "supabase/tests/018_support_properties.test.sql";

// Counterexamples worth keeping, as sequences of [userIndex, supported].
const REGRESSIONS = [
  [[0, true], [0, true], [0, false], [0, false], [0, true]],
  [[0, true], [1, true], [1, false], [0, false], [2, false]],
];

const operation = fc.tuple(
  fc.integer({ min: 0, max: USERS_PER_SEQUENCE - 1 }),
  fc.boolean(),
);
const sequences = [
  ...REGRESSIONS,
  ...fc.sample(fc.array(operation, { minLength: 1, maxLength: MAX_OPS }), {
    seed: SEED,
    numRuns: SEQUENCES,
  }),
];

// The profile alias is derived from the last 8 characters of the id, so every
// account needs a distinct prefix.
const accountId = (n) =>
  `00000098-0000-4000-8000-0000${n.toString(16).padStart(8, "0")}`;
const userId = (sequence, index) => accountId(0x98000000 + sequence * USERS_PER_SEQUENCE + index);
const authorId = accountId(0x98ffff00);

const lines = [];
let planned = 0;
const model = new Set();

sequences.forEach((operations, sequence) => {
  lines.push(`-- sequence ${sequence}: ${operations.map(([u, s]) => `u${u}${s ? "+" : "-"}`).join(" ")}`);
  operations.forEach(([user, supported], step) => {
    const id = userId(sequence, user);
    if (supported) model.add(id);
    else model.delete(id);
    lines.push(
      `select set_config('request.jwt.claim.sub', '${id}', true);`,
      `select is(public.set_support((select id from ctx where name = 'pub'), ${supported}), ` +
        `jsonb_build_object('supported', ${supported}, 'count', ${model.size}), ` +
        `'seq ${sequence} step ${step}: u${user} ${supported ? "supports" : "withdraws"} -> count ${model.size}');`,
    );
    planned += 1;
  });
});

const allUsers = [];
for (let sequence = 0; sequence < sequences.length; sequence += 1) {
  for (let user = 0; user < USERS_PER_SEQUENCE; user += 1) {
    allUsers.push(userId(sequence, user));
  }
}

lines.push(
  "reset role;",
  `select is((select count(*) from public.supports where publication_id = (select id from ctx where name = 'pub')), ${model.size}::bigint, 'final table count equals the model');`,
);
planned += 1;

const header = `-- Generated by scripts/generate-support-properties.mjs (fast-check seed ${SEED}). Do not edit by hand.
-- Property: for any interleaving of supports and withdrawals by several accounts, the
-- count equals the number of distinct accounts currently supporting.
begin;

select plan(${planned});

create temp table ctx (name text primary key, id uuid, doc jsonb);
grant all on table ctx to anon, authenticated;

insert into auth.users (id, instance_id, aud, role, created_at, updated_at)
select u, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', now(), now()
from unnest(array[
  '${authorId}',
${allUsers.map((id) => `  '${id}'`).join(",\n")}
]::uuid[]) as t(u);

set local role authenticated;
select set_config('request.jwt.claim.sub', '${authorId}', true);

insert into ctx (name, id)
select 'branch', (r ->> 'branchId')::uuid
from (select public.create_branch('8f5a6417-5f6d-4f02-a50c-76d97167db99', 'Support properties', 'sp-branch-key-1', repeat('a', 64)) as r) s;

insert into ctx (name, id)
select 'rev', (r ->> 'revisionId')::uuid
from (
  select public.save_revision(
    (select id from ctx where name = 'branch'),
    (select (public.get_branch_head((select id from ctx where name = 'branch')) ->> 'revisionId')::uuid),
    'Canopy',
    '[{"id":"98ff0000-0000-4000-8000-0000000000f1","kind":"shade_canopy","properties":{"label":"Canopy","heightM":4.5},"geometry":{"type":"Polygon","coordinates":[[[-98.19825,19.04358],[-98.19805,19.04358],[-98.19805,19.04372],[-98.19825,19.04372],[-98.19825,19.04358]]]}}]'::jsonb,
    'sp-save-key-001',
    repeat('b', 64)
  ) as r
) s;

insert into ctx (name, id)
select 'pub', (r ->> 'publicationId')::uuid
from (
  select public.publish_revision((select id from ctx where name = 'rev'), 'Support properties', 'Property fixture', 'sp-pub-key-0001', repeat('c', 64)) as r
) s;

`;

const footer = `
select * from finish();
rollback;
`;

const content = `${header}${lines.join("\n")}\n${footer}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== content) {
    console.error(`drift: ${OUTPUT} does not match the generator output`);
    process.exit(1);
  }
  console.log("support properties match");
} else {
  writeFileSync(OUTPUT, content);
  console.log(`wrote ${OUTPUT} (${planned} assertions, seed ${SEED})`);
}
